namespace Sunduk.Geometry
{
    /// <summary>
    /// Вектор мнимой вершины инструмента — положение «программируемой» вершины резца относительно
    /// описанного вокруг пластины квадрата (ISO-концепция направления вершины для коррекции на
    /// радиус при вершине, G41/G42). Определяет сторону материала (наружное/внутреннее точение) и
    /// направление реза вдоль Z.
    /// <br/><br/>
    /// Нумерация в этом проекте соответствует углам квадрата в координатах «X вверх, Z вправо»
    /// (как на экране превью): 3 — нижний левый <c>(-X,-Z)</c> (типовой наружный проходной резец,
    /// точение к -Z), 2 — верхний левый <c>(+X,-Z)</c> (типовой расточной резец, внутреннее точение
    /// к -Z) — эти два значения совпадают с уже использовавшейся в <see cref="ToolTipCompensation"/>
    /// трактовкой «вектор 3 = наружный / вектор 2 = внутренний». Зеркальные по Z углы 4 <c>(-X,+Z)</c>
    /// и 1 <c>(+X,+Z)</c> — наружное/внутреннее точение в обратном направлении (+Z); компенсация
    /// контура их пока не использует (модуль считает для реза к -Z).
    /// </summary>
    public enum ToolNoseVector
    {
        /// <summary>Вектор 3, нижний левый угол <c>(-X,-Z)</c> — наружное точение к -Z.</summary>
        TurningExternal = 3,

        /// <summary>Вектор 2, верхний левый угол <c>(+X,-Z)</c> — внутреннее (расточное) точение к -Z.</summary>
        BoringInternal = 2,

        /// <summary>Вектор 4, нижний правый угол <c>(-X,+Z)</c> — наружное точение к +Z (обратное).</summary>
        TurningExternalBack = 4,

        /// <summary>Вектор 1, верхний правый угол <c>(+X,+Z)</c> — внутреннее точение к +Z (обратное).</summary>
        BoringInternalBack = 1,
    }

    public static class ToolNoseVectorExtensions
    {
        /// <summary>Наружное точение — материал лежит со стороны -X от инструмента (вершина у нижних
        /// углов квадрата). Внутреннее — материал со стороны +X (вершина у верхних углов).</summary>
        public static bool IsExternal(this ToolNoseVector vector)
            => vector is ToolNoseVector.TurningExternal or ToolNoseVector.TurningExternalBack;
    }
}
